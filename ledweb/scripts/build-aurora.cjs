'use strict';
const fs=require('node:fs');
const path=require('node:path');
const zlib=require('node:zlib');
const root=path.resolve(__dirname,'..');
function bundle(){
  const read=name=>fs.readFileSync(path.join(root,'app/aurora',name),'utf8');
  let html=read('index.html').replace('data-demo="true"','data-demo="false"');
  html=html.replace('<link rel="stylesheet" href="/aurora/app.css">',()=>'<style>'+read('app.css')+'</style>');
  for(const [url,file] of [['/aurora/transport.js','transport.js'],['/aurora/app.js','app.js'],['/demo-preview.js','preview.js']]){
    html=html.replace('<script src="'+url+'"></script>',()=>'<script>'+read(file).replace(/<\/script/gi,'<\\/script')+'</script>');
  }
  if(/(?:src|href)="\/(?:aurora|demo-preview)/.test(html))throw Error('Asset sin incluir');
  return html;
}
function build(){
  const html=bundle(),bytes=zlib.gzipSync(Buffer.from(html),{level:9});
  const rows=[];for(let i=0;i<bytes.length;i+=24)rows.push('  '+[...bytes.subarray(i,i+24)].join(','));
  const header='// Generated by node scripts/build-aurora.cjs. Do not edit.\n#pragma once\n#include <pgmspace.h>\nconst uint8_t AURORA_UI[] PROGMEM = {\n'+rows.join(',\n')+'\n};\n';
  fs.writeFileSync(path.join(root,'firmware/LEDWeb/aurora_ui.h'),header);
  fs.mkdirSync(path.join(root,'.build/aurora'),{recursive:true});
  fs.writeFileSync(path.join(root,'.build/aurora/index.html'),html);
  console.log('Aurora: '+Buffer.byteLength(html)+' bytes HTML, '+bytes.length+' bytes gzip');
}
if(require.main===module)build();
module.exports={bundle,build};
